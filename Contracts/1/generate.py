#!/usr/bin/env python3
"""Generate portable leaf bindings and the kit's content-addressed file manifest."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent

def upper(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).upper()

def outputs():
    schema = json.loads((ROOT / 'schemas/host.schema.json').read_text())
    limits = schema['x-limits']
    vocab = {key: value['enum'] for key, value in schema['$defs'].items() if value.get('type') == 'string' and 'enum' in value}
    fields = {key: list(value['properties']) for key, value in schema['$defs'].items() if 'properties' in value}
    writer_required = {key: value['x-writer-required'] for key, value in schema['$defs'].items() if 'x-writer-required' in value}
    tuples = {key: value['minItems'] for key, value in schema['$defs'].items() if 'prefixItems' in value}
    digest = hashlib.sha256((ROOT / 'schemas/host.schema.json').read_bytes()).hexdigest()
    banner = '// Generated by Contracts/1/generate.py; schema SHA-256: ' + digest + '\n'
    swift = banner + 'package enum HostContract {\n'
    ts = banner
    kotlin = banner + 'package sh.swifttui.android.host\n\ninternal object HostContract {\n'
    for key, value in limits.items():
        swift += f'  package static let {key} = {value}\n'
        ts += f'export const {upper(key)} = {value};\n'
        kotlin += f'  const val {upper(key)} = {value}\n'
    for key, value in tuples.items():
        swift += f'  package static let {key}Arity = {value}\n'
        ts += f'export const {upper(key)}_ARITY = {value};\n'
        kotlin += f'  const val {upper(key)}_ARITY = {value}\n'
    for suffix, groups in [('Tokens', vocab), ('Fields', fields), ('WriterRequired', writer_required)]:
        for key, values in groups.items():
            values = sorted(values)
            literals = ', '.join(json.dumps(v) for v in values)
            swift += f'  package static let {key}{suffix}: Set<String> = [{literals}]\n'
            ts += f'export const {upper(key)}_{suffix.upper()} = [{literals}] as const;\n'
            if suffix == 'Tokens':
                kotlin += f'  val {upper(key)}_{suffix.upper()} = setOf({literals})\n'
    swift += '''
  package static func uint64(_ value: String) -> UInt64? {
    guard (1...20).contains(value.utf8.count),
      value.utf8.allSatisfy({ $0 >= 0x30 && $0 <= 0x39 }) else { return nil }
    return UInt64(value)
  }
}
'''
    ts += '''
/** Lossless bounded legacy decimal ingress; writers emit the canonical result. */
export function normalizeWireUInt64(value: unknown): string | undefined {
  if (typeof value !== "string" || value.length < 1 || value.length > 20) return;
  for (let i = 0; i < value.length; i++) {
    const digit = value.charCodeAt(i);
    if (digit < 48 || digit > 57) return;
  }
  let start = 0;
  while (start + 1 < value.length && value.charCodeAt(start) === 48) start++;
  const canonical = start === 0 ? value : value.slice(start);
  if (canonical.length === 20 && canonical > "18446744073709551615") return;
  return canonical;
}
'''
    kotlin += '''}

internal fun normalizeWireUInt64(value: String): String? {
  if (value.length !in 1..20 || value.any { it !in '0'..'9' }) return null
  return value.toULongOrNull()?.toString()
}
'''
    return {'bindings/HostContract.swift': swift, 'bindings/HostContract.ts': ts, 'bindings/HostContract.kt': kotlin}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changed = []
    generated = outputs()
    production = ROOT.parents[1] / 'Sources/SwiftTUIRuntime/Terminal/HostContract.generated.swift'
    swift_source = generated['bindings/HostContract.swift']
    if not production.exists() or production.read_text() != swift_source:
        changed.append(str(production))
        if not args.check: production.write_text(swift_source)
    for name, content in generated.items():
        path = ROOT / name
        if not path.exists() or path.read_text() != content:
            changed.append(name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    entries = {}
    for path in sorted(ROOT.rglob('*')):
        if not path.is_file() or path.name == 'manifest.json' or '__pycache__' in path.parts:
            continue
        name = path.relative_to(ROOT).as_posix()
        # When checking, use expected generated bytes so stale files also dirty the manifest.
        data = generated[name].encode() if name in generated else path.read_bytes()
        entries[name] = {'sha256': hashlib.sha256(data).hexdigest(), 'bytes': len(data)}
    digest = hashlib.sha256(json.dumps(entries, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    manifest = {'formatVersion': 1, 'kitRevision': '1', 'profile': 'swifttui.host-wire/1',
                'minimumReader': 'full-v1-v2', 'schemaDialect': 'https://json-schema.org/draft/2020-12/schema',
                'contentSHA256': digest, 'files': entries,
                'runner': 'conformance/run.py', 'bindingGenerator': 'generate.py',
                'capabilities': {'delta': 'acceptsDeltaFrames', 'styleAppend': 'styleAppend',
                                 'geometry': 'geometryRevisions', 'viewport': 'geometryRevisions+sharedViewport'}}
    content = json.dumps(manifest, indent=2) + '\n'
    path = ROOT / 'manifest.json'
    if not path.exists() or path.read_text() != content:
        changed.append('manifest.json')
        if not args.check: path.write_text(content)
    if args.check and changed:
        raise SystemExit('stale contract outputs: ' + ', '.join(changed))
    print('contract outputs verified' if args.check else 'contract outputs generated')

if __name__ == '__main__': main()
